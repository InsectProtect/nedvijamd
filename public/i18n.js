  const CYR = 'А-Яа-яЁё';
  const phrases = Object.keys(RO).sort((a, b) => b.length - a.length).map((k) => ({
    k,
    v: RO[k],
    re: new RegExp(`(?<![${CYR}])${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![${CYR}])`, 'g')
  }));

